"""STEP 3-4: Inspect the actual CISLR metadata and produce a factual audit.

This script makes NO assumptions about column names, signer availability,
or class structure (per spec section 5). It:

  1. Scans data/raw/ for metadata files (csv / json / parquet / tsv).
  2. Prints their schema (columns, dtypes, row counts, sample rows) so a
     human can map the real columns to the roles the pipeline needs
     (video path, class label, signer id, split hint, duration, fps...).
  3. Writes that raw schema report to research/RAW_SCHEMA_REPORT.md.
  4. If a column_mapping.yaml is present (see configs/column_mapping.yaml),
     it also computes the actual statistics required by section 5:
     videos/classes/signers, per-class and per-signer counts, imbalance,
     duplicates, missing files -- and writes
     results/tables/dataset_statistics.csv plus the two distribution
     figures. If signer information is NOT present in the mapping, it
     says so explicitly and does not proceed to claim anything about
     signer independence (that is enforced downstream in split_data.py).

Usage:
    python src/data/audit_dataset.py --raw-dir data/raw \
        --mapping configs/column_mapping.yaml   # optional, once known
"""
from __future__ import annotations

import argparse
import hashlib
import os
from pathlib import Path

import pandas as pd

SUPPORTED_METADATA_EXTS = {".csv", ".tsv", ".json", ".parquet"}


def find_metadata_files(raw_dir: Path) -> list[Path]:
    return [p for p in raw_dir.rglob("*") if p.suffix.lower() in SUPPORTED_METADATA_EXTS]


def load_any(path: Path) -> pd.DataFrame:
    if path.suffix.lower() == ".csv":
        return pd.read_csv(path)
    if path.suffix.lower() == ".tsv":
        return pd.read_csv(path, sep="\t")
    if path.suffix.lower() == ".json":
        return pd.read_json(path, lines=_looks_like_jsonl(path))
    if path.suffix.lower() == ".parquet":
        return pd.read_parquet(path)
    raise ValueError(f"Unsupported metadata file: {path}")


def _looks_like_jsonl(path: Path) -> bool:
    with open(path, "r") as f:
        first = f.readline().strip()
    return first.startswith("{") and not first.startswith("[")


def report_schema(dfs: dict[str, pd.DataFrame], out_path: Path) -> None:
    lines = ["# Raw CISLR Metadata Schema Report", "",
             "Auto-generated by src/data/audit_dataset.py. No column meaning",
             "is assumed here -- this is purely what is physically present",
             "in the files under data/raw/.", ""]
    for name, df in dfs.items():
        lines.append(f"## {name}")
        lines.append(f"- rows: {len(df)}")
        lines.append(f"- columns: {list(df.columns)}")
        lines.append("")
        lines.append("dtypes:")
        lines.append("```")
        lines.append(df.dtypes.to_string())
        lines.append("```")
        lines.append("")
        lines.append("sample rows:")
        lines.append("```")
        lines.append(df.head(5).to_string())
        lines.append("```")
        lines.append("")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines))
    print(f"[audit] schema report written to {out_path}")


def report_video_only_delivery(raw_dir: Path, out_path: Path,
                               tables_out: Path) -> None:
    """Record the factual limitation when an archive contains videos only."""
    videos = list(raw_dir.rglob("*.mp4"))
    archives = list(raw_dir.rglob("*.zip"))
    lines = [
        "# Raw CISLR Metadata Schema Report", "",
        "## Metadata availability", "",
        "No CSV, TSV, JSON, or Parquet metadata file was found under "
        f"`{raw_dir}`.", "",
        "## Physical inventory", "",
        f"- MP4 files: {len(videos)}",
        f"- ZIP archives: {len(archives)}", "",
        "## Consequence", "",
        "No video-to-label mapping or signer field is available. This delivery "
        "cannot support supervised class statistics, vocabulary selection, "
        "training, or signer-independent evaluation. Filenames are not used "
        "as a proxy for labels or signer identities.",
    ]
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines))
    tables_out.mkdir(parents=True, exist_ok=True)
    pd.DataFrame([
        {"metric": "num_video_files", "value": len(videos)},
        {"metric": "num_zip_archives", "value": len(archives)},
        {"metric": "metadata_files_found", "value": 0},
        {"metric": "num_labeled_records", "value": "not available"},
        {"metric": "num_classes", "value": "not available"},
        {"metric": "signer_metadata_available", "value": False},
        {"metric": "supervised_experiment_eligible", "value": False},
    ]).to_csv(tables_out / "dataset_statistics.csv", index=False)
    print(f"[audit] video-only delivery report written to {out_path}")


def file_hash(path: Path, chunk_size: int = 1 << 20) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(chunk_size), b""):
            h.update(chunk)
    return h.hexdigest()


def run_mapped_audit(df: pd.DataFrame, mapping: dict, raw_dir: Path,
                      tables_out: Path, figures_out: Path) -> None:
    """Compute the actual statistics required by spec section 5, using a
    user-confirmed column_mapping (video_path/label/signer_id/...)."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    label_col = mapping.get("label_col")
    signer_col = mapping.get("signer_col")  # may be None -> not available
    video_col = mapping.get("video_path_col")
    duration_col = mapping.get("duration_col")  # optional
    fps_col = mapping.get("fps_col")  # optional

    if label_col is None or video_col is None:
        raise ValueError(
            "column_mapping.yaml must at least set label_col and "
            "video_path_col before a mapped audit can run."
        )

    n_videos = len(df)
    n_classes = df[label_col].nunique()
    per_class = df[label_col].value_counts()

    stats_rows = [
        {"metric": "num_videos", "value": n_videos},
        {"metric": "num_classes", "value": n_classes},
        {"metric": "videos_per_class_min", "value": per_class.min()},
        {"metric": "videos_per_class_max", "value": per_class.max()},
        {"metric": "videos_per_class_median", "value": per_class.median()},
        {"metric": "class_imbalance_ratio(max/min)", "value": per_class.max() / max(per_class.min(), 1)},
    ]

    signer_available = signer_col is not None and signer_col in df.columns
    stats_rows.append({"metric": "signer_metadata_available", "value": signer_available})
    if signer_available:
        n_signers = df[signer_col].nunique()
        per_signer = df[signer_col].value_counts()
        stats_rows += [
            {"metric": "num_unique_signers", "value": n_signers},
            {"metric": "videos_per_signer_min", "value": per_signer.min()},
            {"metric": "videos_per_signer_max", "value": per_signer.max()},
        ]
    else:
        print(
            "[audit] WARNING: no usable signer column in the mapping. "
            "Signer-independent evaluation (spec section 19) is NOT possible "
            "until real signer metadata is confirmed. This is reported, not worked around."
        )

    # Missing / corrupt file check (paths resolved relative to raw_dir)
    missing = []
    hashes: dict[str, list[str]] = {}
    for _, row in df.iterrows():
        vp = Path(row[video_col])
        full = vp if vp.is_absolute() else raw_dir / vp
        if not full.exists():
            missing.append(str(vp))
        else:
            try:
                h = file_hash(full)
                hashes.setdefault(h, []).append(str(vp))
            except OSError:
                missing.append(str(vp))
    n_missing = len(missing)
    n_duplicate_groups = sum(1 for v in hashes.values() if len(v) > 1)
    stats_rows += [
        {"metric": "missing_or_unreadable_files", "value": n_missing},
        {"metric": "duplicate_file_groups(by_content_hash)", "value": n_duplicate_groups},
    ]

    if duration_col and duration_col in df.columns:
        stats_rows.append({"metric": "duration_seconds_median", "value": df[duration_col].median()})
        stats_rows.append({"metric": "duration_seconds_p95", "value": df[duration_col].quantile(0.95)})
    if fps_col and fps_col in df.columns:
        stats_rows.append({"metric": "fps_mode", "value": df[fps_col].mode().iloc[0] if not df[fps_col].mode().empty else None})

    tables_out.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(stats_rows).to_csv(tables_out / "dataset_statistics.csv", index=False)
    if n_missing:
        pd.Series(missing, name="missing_path").to_csv(tables_out / "missing_files.csv", index=False)

    figures_out.mkdir(parents=True, exist_ok=True)
    plt.figure(figsize=(10, 4))
    per_class.sort_values(ascending=False).plot(kind="bar")
    plt.title("Videos per class (CISLR, selected vocabulary TBD)")
    plt.xlabel("class")
    plt.ylabel("num videos")
    plt.xticks([])
    plt.tight_layout()
    plt.savefig(figures_out / "class_distribution.png", dpi=150)
    plt.close()

    if signer_available:
        plt.figure(figsize=(10, 4))
        per_signer.sort_values(ascending=False).plot(kind="bar")
        plt.title("Videos per signer")
        plt.xlabel("signer")
        plt.ylabel("num videos")
        plt.xticks([])
        plt.tight_layout()
        plt.savefig(figures_out / "signer_distribution.png", dpi=150)
        plt.close()

    print(f"[audit] dataset_statistics.csv written ({n_videos} videos, {n_classes} classes, "
          f"signer_metadata_available={signer_available})")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw-dir", default="data/raw")
    ap.add_argument("--mapping", default=None,
                     help="Path to configs/column_mapping.yaml, once the real schema is known.")
    ap.add_argument("--schema-report-out", default="research/RAW_SCHEMA_REPORT.md")
    ap.add_argument("--tables-out", default="results/tables")
    ap.add_argument("--figures-out", default="results/figures")
    args = ap.parse_args()

    raw_dir = Path(args.raw_dir)
    meta_files = find_metadata_files(raw_dir)
    if not meta_files:
        report_video_only_delivery(raw_dir, Path(args.schema_report_out),
                                   Path(args.tables_out))
        print(f"[audit] No metadata files (.csv/.tsv/.json/.parquet) found under {raw_dir}. "
              "Supervised experiments are blocked until official annotations are supplied.")
        return

    dfs = {str(p.relative_to(raw_dir)): load_any(p) for p in meta_files}
    report_schema(dfs, Path(args.schema_report_out))

    if args.mapping and Path(args.mapping).exists():
        # Keep schema-only audits usable before optional training dependencies
        # have been installed. PyYAML is required only for mapped audits.
        try:
            import yaml
        except ImportError as exc:
            raise RuntimeError(
                "Mapped audit requires PyYAML. Install requirements.txt first."
            ) from exc
        mapping = yaml.safe_load(open(args.mapping))
        primary_key = mapping.get("primary_metadata_file")
        df = dfs[primary_key] if primary_key else next(iter(dfs.values()))
        run_mapped_audit(df, mapping, raw_dir, Path(args.tables_out), Path(args.figures_out))
    else:
        print("[audit] No column_mapping.yaml provided yet -- schema report only. "
              "Fill configs/column_mapping.yaml using the schema above, then re-run with --mapping.")


if __name__ == "__main__":
    main()
